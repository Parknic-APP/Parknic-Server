-- ===== 캐릭터 · 사용자 =====
CREATE TABLE characters
(
    id   SMALLINT PRIMARY KEY,
    name VARCHAR(20) NOT NULL
);

CREATE TABLE users
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider            VARCHAR(20)  NOT NULL,
    provider_id         VARCHAR(255) NOT NULL,
    nickname            VARCHAR(20),
    character_id        SMALLINT REFERENCES characters (id),
    status              VARCHAR(20)  NOT NULL,
    apple_refresh_token TEXT,
    created_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_users_provider UNIQUE (provider, provider_id),
    CONSTRAINT uq_users_nickname UNIQUE (nickname),
    CONSTRAINT ck_users_status CHECK (status IN ('PENDING', 'ACTIVE', 'DELETED'))
);

CREATE TABLE refresh_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id  UUID        NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    used       BOOLEAN     NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

-- ===== 공원 =====
CREATE TABLE parks
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manage_no   VARCHAR(50)      NOT NULL,
    name        VARCHAR(100)     NOT NULL,
    park_type   VARCHAR(20)      NOT NULL,
    address     VARCHAR(255)     NOT NULL DEFAULT '',
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    area_m2     DOUBLE PRECISION NOT NULL DEFAULT 0,
    radius_m    INTEGER          NOT NULL,
    review_only BOOLEAN          NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_parks_manage_no UNIQUE (manage_no),
    CONSTRAINT ck_parks_type CHECK (park_type IN
                                    ('NEIGHBORHOOD', 'CHILDREN', 'SMALL', 'SPORTS', 'WATERFRONT', 'CULTURE',
                                     'HISTORY')),
    CONSTRAINT ck_parks_radius CHECK (radius_m > 0)
);
CREATE INDEX idx_parks_lat_lng ON parks (latitude, longitude);

-- ===== 체크인 · 배지 · 업적 =====
-- 위치 이동 경로 보호: 좌표 컬럼 없음
CREATE TABLE checkin_sessions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    park_id     BIGINT      NOT NULL REFERENCES parks (id),
    status      VARCHAR(20) NOT NULL,
    started_at  TIMESTAMPTZ NOT NULL,
    ended_at    TIMESTAMPTZ,
    fail_reason VARCHAR(30),
    CONSTRAINT ck_checkin_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'FAILED', 'CANCELED'))
);
-- 사용자당 진행 중 세션은 1개만 (동시 시작 요청을 DB가 막음)
CREATE UNIQUE INDEX uq_checkin_in_progress ON checkin_sessions (user_id) WHERE status = 'IN_PROGRESS';
CREATE INDEX idx_checkin_status_started ON checkin_sessions (status, started_at);

CREATE TABLE badges
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    park_id     BIGINT      NOT NULL REFERENCES parks (id),
    earned_date DATE        NOT NULL, -- KST 기준 날짜 (앱이 Kst로 계산)
    earned_at   TIMESTAMPTZ NOT NULL,
    -- 같은 공원 하루 1개 (동시 완료 요청을 DB가 막음)
    CONSTRAINT uq_badges_user_park_date UNIQUE (user_id, park_id, earned_date)
);
CREATE INDEX idx_badges_park_date ON badges (park_id, earned_date); -- 공원 랭킹
CREATE INDEX idx_badges_user_date ON badges (user_id, earned_date); -- 연속 일수

CREATE TABLE achievements
(
    code      VARCHAR(30) PRIMARY KEY,
    name      VARCHAR(50) NOT NULL,
    threshold INTEGER     NOT NULL
);

CREATE TABLE user_achievements
(
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    achievement_cd VARCHAR(30) NOT NULL REFERENCES achievements (code),
    achieved_at    TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, achievement_cd)
);

-- ===== 리뷰 · 신고 · 차단 =====
CREATE TABLE reviews
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    park_id    BIGINT       NOT NULL REFERENCES parks (id),
    rating     SMALLINT     NOT NULL,
    content    VARCHAR(300) NOT NULL,
    hidden     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_reviews_user_park UNIQUE (user_id, park_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_content CHECK (char_length(content) >= 10)
);
CREATE INDEX idx_reviews_park_id ON reviews (park_id, id DESC); -- 커서 페이지네이션

CREATE TABLE review_reports
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   BIGINT      NOT NULL REFERENCES reviews (id) ON DELETE CASCADE,
    reporter_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reason      VARCHAR(20) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_report_review_reporter UNIQUE (review_id, reporter_id),
    CONSTRAINT ck_report_reason CHECK (reason IN ('SPAM', 'ABUSE', 'INAPPROPRIATE', 'OTHER'))
);
CREATE INDEX idx_review_reports_reporter ON review_reports (reporter_id);

CREATE TABLE user_blocks
(
    blocker_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    blocked_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT ck_blocks_not_self CHECK (blocker_id <> blocked_id)
);
CREATE INDEX idx_user_blocks_blocked ON user_blocks (blocked_id);

